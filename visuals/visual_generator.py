#   DASHBOARD   #

class Dashboard(App[None]):
    """Main Textual application for the Fly-in drone simulation.

    The dashboard combines the airspace map, event log, drone table,
    simulation summary, and keyboard controls into one interface.
    """

    TITLE = "FlyIn - Drone Traffic Simulation"

    BINDINGS = [
        ("q", "quit", "Quit"),
        ("Q", "quit", "Quit"),
        ("p", "toggle_pause", "Pause / Resume"),
        ("P", "toggle_pause", "Pause / Resume"),
        ("s", "step", "Step"),
        ("S", "step", "Step"),
        ("m", "change_map", "Change Map"),
        ("M", "change_map", "Change Map"),
        ("r", "restart", "Restart"),
        ("R", "restart", "Restart"),
    ]

    CSS = """
    Screen {
        layout: vertical
    }

    /* AREA BETWEEN HEADER & FOOTER*/
    #main {
        width: 100%;
        height: 1fr;
        layout: vertical;
    }

    /* AIRSPACE MAP & EVENT LOG*/
    #top {
        width: 100%;
        height: 2fr;
        layout: horizontal;
    }

    /* AIRSPACE MAP */
    #map {
        width: 3fr;
        height: 100%;
    }

    /* EVENT LOG */
    #events {
        width: 1fr;
        height: 100%;
        border: round yellow;
        padding: 1;
        overflow-y: auto;
    }

    /* BOTTOM SECTION */
    #bottom {
        width: 100%;
        height: 1fr;
        layout: horizontal;
    }

    /* DRONE TABLE */
    #drones {
        width: 6fr;
        height: 100%;
        border: round green;
    }

    /* SUMMARY */
    #summary {
        width: 1fr;
        height: 100%;
        border: round magenta;
        padding: 1;
        overflow: hidden;
    }
    """

    def __init__(
        self,
        engine: Engine,
        map_path: str
    ) -> None:
        """Initialize the simulation dashboard.

        Args:
            engine: Simulation engine controlling the drones and map.
            map_path: Path of the map currently being displayed.
        """
        super().__init__()

        self.paused = False
        self.engine = engine
        self.map_path = map_path
        self.sub_title = map_path

    # LAYOUT
    def compose(self) -> ComposeResult:
        """Build the complete dashboard layout.

        Returns:
            ComposeResult: The Textual widgets forming the dashboard.
        """

        yield Header()

        with Container(id="main"):

            # TOP
            with Horizontal(id="top"):

                yield AirspaceMap(self.engine, id="map")

                yield EventLog(self.engine, id="events")

            # BOTTOM
            with Horizontal(id="bottom"):

                yield DroneTable(self.engine, id="drones")

                yield Summary(self.engine, id="summary")

        yield Footer()

    # MOUNT
    def on_mount(self) -> None:
        """Initialize the dashboard and start the simulation timer.

        The dashboard is updated immediately after mounting and then
        simulation steps are executed automatically every second.
        """
        # Otherwise widget might be blank/stale
        self.update_dashboard()

        # Run one simulation step every second.
        self.set_interval(1.0, self.run_simulation)

    # SIMULATION
    def run_simulation(self) -> None:
        """Execute one simulation step and refresh the dashboard.

        A step is skipped when the simulation is paused or has already
        finished.
        """
        # if paused noting should happen
        if self.paused:
            return
        # if all derones at end_hub, dont continue
        if self.engine.is_finished():
            return

        self.engine.simulation()
        self.update_dashboard()

    # Below are actions: when u do the action,
    # what happens.

    # PAUSE ACTION
    def action_toggle_pause(self) -> None:
        """Toggle the simulation between paused and running states."""
        self.paused = not self.paused

    # STEP ACTION
    def action_step(self) -> None:
        """Execute exactly one simulation step.

        The step is ignored if the simulation has already finished.
        """
        if self.engine.is_finished():
            return

        self.engine.simulation()
        self.update_dashboard()

    # MAP SELECTION OPTION
    def action_change_map(self) -> None:
        """Open the map selection dialog.

        All ``.txt`` files under the ``maps`` directory are discovered and
        presented as selectable maps.
        """

        # collect all maps
        try:
            maps = sorted(Path("maps").rglob("*.txt"))
        except Exception:
            raise ValueError("Map files in .txt formats are missing")

        # Label and value
        options = [
            (str(path), str(path))
            for path in maps
        ]

        self.push_screen(MapSelector(options), self.map_selected)

    # RESET
    def action_restart(self) -> None:
        """Reset the current simulation to its initial state."""
        self.engine.reset()

    def map_selected(self, map_path: str | None) -> None:
        """Load a selected map and replace the current simulation engine.

        Args:
            map_path: Path of the selected map, or ``None`` if no map
                was selected.
        """

        if map_path is None:
            return

        parsed = Parser(map_path)
        graph_object = parsed.parser()

        self.engine = Engine(graph_object)
        self.map_path = map_path
        self.sub_title = map_path

        # Find the widget whose ID is map 
        # and make sure it is an AirspaceMap. Slly for others

        # AIRSPACE MAP
        airspace_map = self.query_one("#map", AirspaceMap)

        # EVENT LOG
        event_log = self.query_one("#events", EventLog)

        # DRONE TABLE
        drone_table = self.query_one("#drones", DroneTable)

        # SUMMARY
        summary = self.query_one("#summary", Summary)

        # Reuse existing widget but point them to new engine
        airspace_map.engine = self.engine
        event_log.engine = self.engine
        drone_table.engine = self.engine
        summary.engine = self.engine

        # after changing maps, simulation starts again
        self.paused = False

        # show new map/state
        self.update_dashboard()

    # UPDATE DASHBOARD
    def update_dashboard(self) -> None:
        """Refresh every visual component of the dashboard.

        The event log, drone table, summary, and airspace map are updated
        using the current state of the simulation engine.
        """

        # EVENT LOG
        event_log = self.query_one("#events", EventLog)
        event_log.update_log()

        # DRONE TABLE
        drone_table = self.query_one("#drones", DroneTable)
        drone_table.update_table()

        # SUMMARY
        summary = self.query_one("#summary", Summary)
        summary.update_summary()

        # AIRSPACE MAP
        airspace_map = self.query_one("#map", AirspaceMap)
        airspace_map.refresh_map()
