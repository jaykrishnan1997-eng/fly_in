#  EVENT LOG  #

class EventLog(VerticalScroll):
    """Display the events generated by the simulation."""

    TITLE = "EVENT LOG"

    # the styling language used in Textual
    # CSS (Cascading Style Sheets) adapted for terminal UIs.
    DEFAULT_CSS = """
    EventLog {
        width: 100;
        height: 100;
        padding: 1;
        overflow-y: auto;
    }
    """

    def __init__(
        self,
        engine: Engine,
        **kwargs: Any,
    ) -> None:
        """Initialize the event log.

        Args:
            engine: The simulation engine containing the event history.
            **kwargs: Additional arguments passed to the Textual widget.
        """
        super().__init__(**kwargs)

        self.engine = engine

    def update_log(self) -> None:
        """Refresh the event log using the engine's current events.

        The existing widgets are removed and replaced by a single widget
        containing all recorded simulation events.
        """
        events = self.engine.event_log

        self.remove_children()

        if not events:
            self.mount(Static("No events yet."))
            return

        self.mount(
            Static(
                "\n".join(str(event) for event in events)
            )
        )


#   SUMMARY   #

class Summary(Static):
    """Display statistics describing the current simulation state."""

    TITLE = "SUMMARY"

    DEFAULT_CSS = """
    Summary {
        width: 100%;
        height: 100%;
        padding: 1;
        overflow: hidden;
    }
    """

    def __init__(
        self,
        engine: Engine,
        **kwargs: Any,
    ) -> None:
        """Initialize the simulation summary.

        Args:
            engine: The simulation engine providing the statistics.
            **kwargs: Additional arguments passed to the Textual widget.
        """
        super().__init__(**kwargs)

        self.engine = engine

    def update_summary(self) -> None:
        """Refresh the displayed simulation statistics.

        The summary shows the total number of drones, drones currently in
        connections, drones in transit, completed drones, total path cost,
        and the number of simulation ticks.
        """
        total_drones = self.engine.graph.total_drones

        drones_in_connections = sum(
            len(drones)
            for drones in self.engine.connection_stat.values()
        )

        drones_in_transit = 0

        for zone in self.engine.zone_stat:
            if zone not in (
                self.engine.graph.start_hub,
                self.engine.graph.end_hub,
            ):
                drones_in_transit += len(
                    self.engine.zone_stat[zone]
                )

        completed_drones = (
            self.engine.zone_occupancy.get(self.engine.graph.end_hub, 0)
        )

        tpc = int(self.engine.total_path_cost - self.engine.graph.total_drones)
        self.update(
            f"Total Drones: {total_drones}\n"
            f"Drones in Connection: {drones_in_connections}\n"
            f"Drones in Transit: {drones_in_transit}\n"
            f"Completed Drones: {completed_drones}\n"
            f"Total path cost: {tpc}\n"
            f"Total turns: {self.engine.ticks}\n"
        )


#  DRONE TABLE  #

class DroneTable(DataTable[str]):
    """Display the current state and route of every drone."""

    TITLE = "DRONE TABLE"

    DEFAULT_CSS = """
    Dronetable {
        width: 100%;
        height: 100%;
    }
    """

    def __init__(
        self,
        engine: Engine,
        **kwargs: Any,
    ) -> None:
        """Initialize the drone table.

        Args:
            engine: The simulation engine containing the drone states.
            **kwargs: Additional arguments passed to the Textual widget.
        """
        super().__init__(**kwargs)

        self.engine = engine

    def on_mount(self) -> None:
        """Create the columns when the table is mounted.

        The columns show the drone ID, current zone, remaining path,
        current status, and whether the drone is waiting.
        """

        self.add_columns(
            "DRONE_ID",
            "CURRENT ZONE",
            "PATH (NEXT -> ...)",
            "STATUS",
            "WAITING",
        )

    def update_table(self) -> None:
        """Refresh the table with the current state of all drones.

        The existing rows are removed and rebuilt from the engine's
        ``drones_stat`` data.
        """

        self.clear()

        for drone in self.engine.drones_stat:
            path = self.engine.drones_stat[drone]

            # Convert the list before slicing since
            # drones_stat stores path as deque
            path_list = list(path)

            if len(path_list) > 1:

                drone_path = " -> ".join(
                    zone.name
                    for zone in path_list[1:]
                )
            else:
                drone_path = ""

            # STATUS
            if drone.current_zone == self.engine.graph.end_hub:
                status = "IN_END_ZONE"
            else:
                status = "IN_TRANSIT"

            # WAITING
            if drone.current_zone == self.engine.graph.end_hub:
                waiting = "--"
            else:
                if drone in self.engine.waiting:
                    waiting = "YES"
                else:
                    waiting = "NO"

            self.add_row(
                str(drone.id),
                str(drone.current_zone.name),
                drone_path,
                status,
                waiting,
            )


