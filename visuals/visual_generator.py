class MapSelector(ModalScreen[str | None]):
    """Display a modal window allowing the user to select a map."""

    DEFAULT_CSS = """

    MapSelector {
        align: center middle;
    }

    #map-dialog {
        width: 70;
        height: auto;
        max-height: 80%;
        padding: 2;
        border: round cyan;
        background: $surface;
    }

    #map-title {
        width: 100%;
        content-align: center middle;
        margin-bottom: 1;
        text-style: bold;
    }

    #map-select {
        width: 100%
    }
    """

    def __init__(
        self,
        options: list[tuple[str, str]],
    ) -> None:
        """Initialize the map selection screen.

        Args:
            options: Map names and values displayed in the selection widget.
        """
        super().__init__()

        self.options = options

    def compose(self) -> ComposeResult:
        """Build the map selection interface.

        Returns:
            ComposeResult: The Textual widgets that form the modal screen.
        """
        with Container(id="map-dialog"):
            yield Static("Select Map", id="map-title")

            yield Select(
                self.options,
                prompt="Choose a map...",
                id="map-select",
            )

    def on_select_changed(
        self,
        event: Select.Changed,
    ) -> None:
        """Handle a map selection made by the user.

        Args:
            event: The Textual selection-change event containing the
                selected map value.
        """
        # Return the selected map

        if event.value is Select.BLANK:
            return

        # close modal and send selected value back to dashboard
        self.dismiss(str(event.value))

